import { useState } from "react";
import { createFileRoute, Link, notFound } from "@tanstack/react-router";
import { ArrowLeft, ArrowRight, ArrowUpRight } from "lucide-react";
import { PageShell } from "@/components/PageShell";
import { useLocale } from "@/lib/locale-context";
import { SITE } from "@/lib/site";
import { seoHead, absUrl, publisherRef } from "@/lib/seo";
import { SERIES, episodeBySlug, type Episode } from "@/lib/history-series";

export const Route = createFileRoute("/labs/history/$episode")({
  loader: ({ params }) => {
    const e = episodeBySlug(params.episode);
    if (!e) throw notFound();
    return { slug: e.slug };
  },
  head: ({ match, params }) => {
    const e = episodeBySlug(params.episode);
    if (!e) return seoHead(match, { title: SITE.name, description: SITE.description, noindex: true });
    return seoHead(match, {
      title: { en: `${e.title.en} — ${SERIES.title.en}, ${SITE.name} Labs`, fr: `${e.title.fr} — ${SERIES.title.fr}, ${SITE.name} Labs` },
      description: e.dek,
      image: absUrl(e.poster, "en"),
      imageAlt: e.beats[0].alt,
      jsonLd: (locale, url) => [{
        "@context": "https://schema.org",
        "@type": "LearningResource",
        name: e.title[locale],
        description: e.dek[locale],
        url,
        image: absUrl(e.poster, "en"),
        publisher: publisherRef,
        inLanguage: locale === "fr" ? "fr-CA" : "en-CA",
        learningResourceType: "Video lesson",
        educationalLevel: locale === "fr" ? "13 ans et plus" : "Ages 13 and up",
        isAccessibleForFree: true,
        isPartOf: { "@type": "CreativeWorkSeries", name: SERIES.title[locale] },
        about: ["Discovery of insulin", "World models", "Generative AI"],
        citation: e.sources.map(s => s.url),
      }],
    });
  },
  component: EpisodePage,
});

