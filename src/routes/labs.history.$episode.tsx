function SectionHead({ id, title, kicker }: { id: string; title: string; kicker?: string }) {
  return (
    <div className="relative pt-3 border-t-[3px] border-night">
      <span className="absolute left-0 -top-[3px] h-[3px] w-14 bg-signal" aria-hidden="true" />
      {kicker && <p className="kicker mt-1">{kicker}</p>}
      <h2 id={id} className="masthead-serif text-[1.75rem] sm:text-[2.05rem] mt-1">{title}</h2>
    </div>
  );
}

type Tab = "when" | "where" | "who" | "what";

/** Who, where, when, what: one panel at a time. */
function StoryExplorer({ e }: { e: Episode }) {
  const { locale, pick } = useLocale();
  const fr = locale === "fr";
  const [tab, setTab] = useState<Tab>("who");
  const tabs: { id: Tab; label: string }[] = [
    { id: "who", label: fr ? "Qui" : "Who" },
    { id: "where", label: fr ? "Où" : "Where" },
    { id: "when", label: fr ? "Quand" : "When" },
    { id: "what", label: fr ? "Ce qu'ils faisaient" : "What they did" },
  ];
  const panelId = (t: Tab) => `story-panel-${t}`;
  return (
    <div className="mt-6">
      <div role="tablist" aria-label={fr ? "Explorer l'histoire" : "Explore the story"} className="flex flex-wrap gap-2">
        {tabs.map(t => (
          <button
            key={t.id}
            type="button"
            role="tab"
            id={`story-tab-${t.id}`}
            aria-selected={tab === t.id}
            aria-controls={panelId(t.id)}
            onClick={() => setTab(t.id)}
            className={`press min-h-[44px] rounded-full border px-4 text-[0.95rem] font-semibold transition-colors ${tab === t.id ? "bg-ink text-white border-ink" : "bg-surface border-line hover:border-ink"}`}
          >
            {t.label}
          </button>
        ))}
      </div>

      <div id={panelId(tab)} role="tabpanel" aria-labelledby={`story-tab-${tab}`} className="mt-6">
        {tab === "who" && (
          <ul className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
            {e.people.map(p => (
              <li key={p.name} className="border border-line rounded-[8px] p-5">
                <p className="hl text-[1.3rem]">{p.name}</p>
                <p className="text-[0.85rem] font-semibold text-brass-ink mt-0.5">{pick(p.role)}</p>
                <p className="mt-2 text-[0.98rem] leading-relaxed text-muted-ink">{pick(p.text)}</p>
              </li>
            ))}
          </ul>
        )}
        {tab === "where" && (
          <div className="grid gap-6 md:grid-cols-12 items-start">
            <p className="md:col-span-7 font-serif text-[1.2rem] leading-relaxed">{pick(e.where)}</p>
            <p className="md:col-span-5 bg-ice rounded-[8px] p-5 text-[0.98rem] leading-relaxed">
              {fr ? "Dans la version de l'IA, la fenêtre donne sur une rue commerçante animée. Cette vue est inventée." : "In the AI version, the window looks onto a busy shopping street. That view is invented."}
            </p>
          </div>
        )}
        {tab === "when" && (
          <>
            <p className="font-serif text-[1.15rem] leading-relaxed max-w-3xl">{pick(e.when)}</p>
            <ol className="mt-5 border-t-2 border-ink">
              {e.timeline.map((t, i) => (
                <li key={i} className="grid gap-1 sm:grid-cols-[180px_1fr] py-3.5 border-b border-line">
                  <span className="font-bold text-brass-ink">{pick(t.date)}</span>
                  <span className="text-[1rem] leading-relaxed">{pick(t.text)}</span>
                </li>
              ))}
            </ol>
          </>
        )}
        {tab === "what" && (
          <ol className="grid gap-3 max-w-3xl">
            {e.what.map((w, i) => (
              <li key={i} className="flex gap-4 bg-ice rounded-[8px] p-4">
                <span aria-hidden="true" className="masthead-serif text-[1.8rem] leading-none text-brass-ink w-6">{i + 1}</span>
                <span className="text-[1.02rem] leading-relaxed">{pick(w)}</span>
              </li>
            ))}
          </ol>
        )}
      </div>
    </div>
  );
}

